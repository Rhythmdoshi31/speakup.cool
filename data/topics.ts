const topicQueues: Partial<
  Record<Mode, Partial<Record<Category, string[]>>>
> = {};

function shuffleArray<T>(array: T[]): T[] {
  const shuffled = [...array];

  for (let i = shuffled.length - 1; i > 0; i--) {
    // Cryptographically stronger randomness when available
    // while still falling back safely in the browser.
    const random =
      typeof crypto !== "undefined" && crypto.getRandomValues
        ? (() => {
            const values = new Uint32Array(1);
            crypto.getRandomValues(values);
            return values[0] / (0xffffffff + 1);
          })()
        : Math.random();

    const j = Math.floor(random * (i + 1));

    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled;
}

function createQueue(
  mode: Mode,
  category: Category,
  previousTopic?: string,
): string[] {
  const source = topics[mode][category];

  if (!source || source.length === 0) {
    return [];
  }

  let shuffled = shuffleArray(source);

  // Prevent the first topic of the new cycle from being
  // the same as the last topic of the previous cycle.
  if (
    previousTopic &&
    shuffled.length > 1 &&
    shuffled[0] === previousTopic
  ) {
    const swapIndex = 1 + Math.floor(
      Math.random() * (shuffled.length - 1),
    );

    [shuffled[0], shuffled[swapIndex]] = [
      shuffled[swapIndex],
      shuffled[0],
    ];
  }

  return shuffled;
}

export function getRandomTopic(
  mode: Mode,
  category: Category,
  currentTopic?: string,
): string {
  const modeQueues = topicQueues[mode] ?? {};
  topicQueues[mode] = modeQueues;

  let queue = modeQueues[category];

  // Create a new shuffled queue if one doesn't exist.
  if (!queue || queue.length === 0) {
    queue = createQueue(mode, category, currentTopic);
  }

  const nextTopic = queue.shift();

  modeQueues[category] = queue;

  return nextTopic ?? "Something to talk about";
}